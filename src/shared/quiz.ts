/** Reuse the existing AI request queue for on-demand quizzes. */
export function buildQuizPrompt(topic?: string): string {
  return [
    "日本語で4択クイズを1問出してください。",
    `テーマ: ${topic?.trim() || "AI・プログラミングの基礎"}`,
    "指定テーマそのものについて出題してください。人物名ならその人物について扱い、AIやプログラミングなど別のテーマへ置き換えないでください。",
    "テーマが人物名だけの場合、このターンではクイズを作らず「どの方についてですか？出題の元になる説明や資料本文を送ってください」と確認だけしてください。人物を知っているつもりでも例外はありません。",
    "資料や説明が与えられた場合はその内容だけを根拠に出題し、書籍名・経歴・数字を補完しないでください。",
    "正解が1つに決まる、確かな知識だけを問う問題にしてください。",
    "未確認の最新ニュースや未来予測は扱わないでください。",
    "問題文、1️⃣〜4️⃣の重複しない選択肢、正解と短い解説の順で出力してください。",
    "正解番号と解説は必ず一緒にDiscordの ||正解: … 解説: …|| で囲み、先に答えが見えないようにしてください。",
    "最後に「答えを考えたら、ネタバレ部分をタップして確認してください」と案内してください。",
    "この依頼では次の一手の提案は不要です。全体600文字以内。",
  ].join("\n");
}
